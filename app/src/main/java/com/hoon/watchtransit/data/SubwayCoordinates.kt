    fun get(stationName: String): Pair<Double, Double>? {
        val clean = stationName.removeSuffix("역").trim()
        coords[clean]?.let { return it }

        // 괄호 부역명 제거 (예: 청량리(서울시립대입구) -> 청량리)
        val baseName = clean.split("(")[0].trim()
        coords[baseName]?.let { return it }

        // 부분 일치 검색
        for ((k, v) in coords) {
            if (clean.contains(k) || k.contains(clean)) {
                return v
            }
        }
        return null
    }
